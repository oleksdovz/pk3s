// Package starter renders an annotated cluster spec for `pk3s init`: the
// chosen values are active, every alternative found on the host and every
// optional section is included as a comment.
package starter

import (
	"fmt"
	"net/netip"
	"sort"
	"strings"
	"time"

	"gopkg.in/yaml.v3"

	"github.com/oleksdovz/pk3s/internal/pve"
	"github.com/oleksdovz/pk3s/internal/spec"
)

// Options carries information that needs I/O to obtain.
type Options struct {
	Now time.Time
	// StableVersion is what the "stable" channel resolves to ("" if unknown).
	StableVersion string
	Version       string // pk3s version
}

type writer struct{ b strings.Builder }

func (w *writer) line(format string, args ...any) { fmt.Fprintf(&w.b, format+"\n", args...) }
func (w *writer) blank()                          { w.b.WriteString("\n") }

// q renders a YAML scalar safely (quotes when needed).
func q(v any) string {
	out, err := yaml.Marshal(v)
	if err != nil {
		return fmt.Sprint(v)
	}
	return strings.TrimSpace(string(out))
}

func list(v []string) string {
	if len(v) == 0 {
		return "[]"
	}
	parts := make([]string, len(v))
	for i, s := range v {
		parts[i] = q(s)
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

// Headroom is the number of extra consecutive free IDs reserved for scaling.
const Headroom = 10

// FreeCTIDStart returns the first ID at or after from (stepping by 100)
// with n consecutive IDs unused by any guest in the Proxmox cluster.
func FreeCTIDStart(inv *pve.Inventory, from, n int) int {
	used := map[int]bool{}
	for _, g := range inv.Guests {
		used[g.VMID] = true
	}
	for start := from; start < 1_000_000; start += 100 {
		free := true
		for i := 0; i < n; i++ {
			if used[start+i] {
				free = false
				break
			}
		}
		if free {
			return start
		}
	}
	return from
}

// usedIDs lists guests with IDs in [from, to].
func usedIDs(inv *pve.Inventory, from, to int) []string {
	var out []string
	for _, g := range inv.Guests {
		if g.VMID >= from && g.VMID <= to {
			out = append(out, fmt.Sprintf("%d (%s)", g.VMID, g.Name))
		}
	}
	return out
}

// usedAddresses lists addresses known on the host (guests and bridges).
func usedAddresses(inv *pve.Inventory) []string {
	var out []string
	for _, b := range inv.Bridges {
		if b.Address != "" {
			out = append(out, fmt.Sprintf("%s (host %s)", b.Address, b.Name))
		}
	}
	for _, g := range inv.Guests {
		for _, ip := range g.IPs {
			out = append(out, fmt.Sprintf("%s (%s %d %s)", ip, g.Type, g.VMID, g.Name))
		}
	}
	sort.Slice(out, func(i, j int) bool {
		a, _ := netip.ParseAddr(strings.Fields(out[i])[0])
		b, _ := netip.ParseAddr(strings.Fields(out[j])[0])
		return a.Less(b)
	})
	return out
}

func gib(b int64) int64 { return b >> 30 }

// Render returns the annotated spec. s holds the chosen values (defaults
// already filled from the inventory).
func Render(s spec.ClusterSpec, inv *pve.Inventory, o Options) string {
	w := &writer{}
	w.line("# pk3s cluster spec, generated by `pk3s init` on %s", o.Now.UTC().Format("2006-01-02 15:04 UTC"))
	w.line("# Host: %s, Proxmox VE %s, kernel %s, %s, cgroup v2: %v", inv.Node, inv.PVEVersion, inv.Kernel, inv.Arch, inv.CgroupV2)
	w.line("#")
	w.line("# Active lines are the values pk3s chose for this host. Commented lines")
	w.line("# list the alternatives found on the host and optional settings.")
	w.line("# Review, set network.first_ip, then:")
	w.line("#   pk3s plan  -f <this file>   # validate and show the plan (changes nothing)")
	w.line("#   pk3s apply -f <this file>")
	w.blank()

	w.line("# Cluster name: state in /var/lib/pk3s/clusters/<name>, Proxmox tag pk3s-<name>.")
	w.line("name: %s", q(s.Name))
	w.line("# Containers are named <prefix>-main1.. (servers) and <prefix>-node1.. (agents).")
	if s.HostnamePrefix != "" {
		w.line("hostname_prefix: %s", q(s.HostnamePrefix))
	} else {
		w.line("# hostname_prefix: %s   # default: the cluster name", q(s.Name))
	}
	w.line("node: %s", q(s.Node))
	if len(inv.Nodes) > 1 {
		w.line("# Proxmox cluster nodes: %s (pk3s places all containers on the node it runs on)", strings.Join(inv.Nodes, ", "))
	}
	w.blank()

	w.line("# Servers (main): 1, 3, 5 or 7. Always embedded etcd; servers can be added later.")
	w.line("servers: %d", s.Servers)
	w.line("# Agents (node): workers. Change later and `apply` again to scale.")
	w.line("agents: %d", s.Agents)
	w.line("# First CT ID; nodes use consecutive free IDs.")
	w.line("ctid_start: %d", s.CTIDStart)
	last := s.CTIDStart + s.TotalNodes() - 1
	if busy := usedIDs(inv, s.CTIDStart, last+Headroom); len(busy) == 0 {
		w.line("# Checked: CT IDs %d-%d for this spec and %d-%d (room to scale) are free in the Proxmox cluster.",
			s.CTIDStart, last, last+1, last+Headroom)
	} else {
		w.line("# WARNING: CT IDs in %d-%d already in use: %s", s.CTIDStart, last+Headroom, strings.Join(busy, ", "))
	}
	if len(inv.Guests) > 0 {
		var ids []string
		for _, g := range inv.Guests {
			ids = append(ids, fmt.Sprintf("%d %s", g.VMID, g.Name))
		}
		w.line("# CT/VM IDs in use: %s", strings.Join(ids, ", "))
	}
	w.blank()

	w.line("# LXC template (Debian 12/13 or Ubuntu LTS 'standard' templates are supported).")
	w.line("template:")
	w.line("  storage: %s", q(s.Template.Storage))
	w.line("  name: %s", q(s.Template.Name))
	w.line("  download: %v   # true: run 'pveam download' if the template is missing", s.Template.Download)
	if len(inv.Templates) > 0 {
		w.line("  # Templates on this host (storage: name):")
		for _, t := range inv.Templates {
			store := strings.SplitN(t.VolID, ":", 2)[0]
			mark := ""
			if !strings.HasPrefix(t.Name(), "debian-") && !strings.HasPrefix(t.Name(), "ubuntu-") {
				mark = "   (not supported: no apt/systemd)"
			}
			w.line("  #   %s: %s%s", store, t.Name(), mark)
		}
	} else {
		w.line("  # No templates found. Set download: true and a name from 'pveam available --section system'.")
	}
	w.blank()

	w.line("# Storage for container root disks.")
	w.line("rootfs_storage: %s", q(s.RootfsStorage))
	w.line("# Storages on this host:")
	for _, st := range inv.Storages {
		use := []string{}
		if st.Has("rootdir") {
			use = append(use, "root disks")
		}
		if st.Has("vztmpl") {
			use = append(use, "templates")
		}
		if len(use) == 0 {
			continue
		}
		state := ""
		if !st.Active {
			state = ", INACTIVE"
		}
		w.line("#   %-24s %-8s %6d GiB free of %6d GiB  (%s%s)", st.ID, st.Type, gib(st.Avail), gib(st.Total), strings.Join(use, ", "), state)
	}
	w.blank()

	w.line("# Defaults are starting points, not sizing advice.")
	w.line("# k3s documents: server >= 2 CPU / 2 GiB (sizing table starts at 4 GiB), agent >= 1 CPU / 512 MiB.")
	w.line("server_resources: {cores: %d, memory_mib: %d, disk_gib: %d}", s.Server.Cores, s.Server.MemoryMiB, s.Server.DiskGiB)
	w.line("agent_resources:  {cores: %d, memory_mib: %d, disk_gib: %d}", s.Agent.Cores, s.Agent.MemoryMiB, s.Agent.DiskGiB)
	w.blank()

	w.line("network:")
	w.line("  bridge: %s", q(s.Network.Bridge))
	for _, b := range inv.Bridges {
		gw := ""
		if b.Gateway != "" {
			gw = ", gateway " + b.Gateway
		}
		w.line("  #   %-10s %s%s", b.Name, orNone(b.CIDR), gw)
	}
	w.line("  # Static IPv4 of the first server; the others get the next free addresses.")
	w.line("  first_ip: %s", q(s.Network.FirstIP))
	if used := usedAddresses(inv); len(used) > 0 {
		w.line("  # Known addresses in use (devices outside Proxmox are checked by ping in 'pk3s plan'):")
		for _, u := range used {
			w.line("  #   %s", u)
		}
	}
	w.line("  prefix: %d", s.Network.Prefix)
	w.line("  gateway: %s", q(s.Network.Gateway))
	w.line("  dns: %s", list(s.Network.DNS))
	if s.Network.SearchDomain != "" {
		w.line("  search_domain: %s", q(s.Network.SearchDomain))
	} else {
		w.line("  # search_domain: lan")
	}
	w.line("  # vlan: 30     # VLAN tag on the bridge port (0 = untagged)")
	w.line("  # mtu: 9000    # 0 = bridge default")
	w.blank()

	w.line("# Per-container network overrides (keys: main1.., node1..). Unset fields use the defaults above.")
	w.line("# node_network:")
	w.line("#   - node: node2")
	w.line("#     ip: 192.168.0.90")
	w.line("#     gateway: 192.168.0.254")
	w.line("#     dns: [1.1.1.1, 9.9.9.9]")
	w.blank()

	w.line("k3s:")
	stable := ""
	if o.StableVersion != "" {
		stable = " (stable is " + o.StableVersion + " now)"
	}
	w.line("  # Exact release (v1.37.2+k3s1) or channel (stable, latest, v1.36)%s.", stable)
	w.line("  # A channel is pinned to its current release at deploy time and never upgrades a running cluster.")
	w.line("  version: %s", q(s.K3s.Version))
	w.line("  # disable: [traefik, servicelb]   # bundled ingress / LoadBalancer")
	w.line("  # tls_sans: [k3s.lan]             # extra names/IPs for the API certificate")
	w.line("  cluster_cidr: %s", q(s.K3s.ClusterCIDR))
	w.line("  service_cidr: %s", q(s.K3s.ServiceCIDR))
	w.blank()

	w.line("security:")
	w.line("  # privileged: community-tested; container root is host root (see docs/SECURITY.md).")
	w.line("  # unprivileged-experimental: keeps host isolation, not documented by k3s, may fail.")
	w.line("  profile: %s", q(s.Security.Profile))
	w.line("  # Must be true for the privileged profile.")
	w.line("  acknowledge_privileged_risk: %v", s.Security.AcknowledgePrivilegedRisk)
	w.line("  tun_device: %v   # pass /dev/net/tun (VPN / WireGuard pods)", s.Security.TunDevice)
	w.line("  fuse: %v         # Proxmox advises against FUSE in containers", s.Security.Fuse)
	w.blank()

	w.line("host:")
	w.line("  # Write /etc/modules-load.d/pk3s.conf and load the k3s kernel modules.")
	w.line("  load_kernel_modules: %v", s.Host.LoadKernelModules)
	w.blank()

	w.line("# Host directory per node for the local-path StorageClass (PVC data on the host).")
	w.line("# Each node gets <host_path>/<cluster>/<hostname> at /var/lib/rancher/k3s/storage.")
	w.line("persistent_data:")
	w.line("  enabled: %v", s.Persistent.Enabled)
	if s.Persistent.HostPath != "" {
		w.line("  host_path: %s", q(s.Persistent.HostPath))
	} else {
		w.line("  # host_path: /data/k3s-storage")
	}
	w.blank()

	w.line("os:")
	w.line("  nfs_client: %v   # install nfs-common; host loads nfs/nfsv4", s.OS.NFSClient)
	w.line("  # extra_packages: [htop, jq]")
	w.blank()

	w.line("access:")
	w.line("  # No root password is set; use 'pct enter <id>' or an SSH key.")
	w.line("  # ssh_public_key_file: /root/.ssh/authorized_keys")
	w.line("  timezone: %s   # 'host' or an IANA name; host is %s", q(s.Access.Timezone), orNone(inv.HostTimezone))
	w.blank()

	w.line("# Proxmox autostart: main first, nodes after; shutdown runs in reverse (main last).")
	w.line("onboot: %v", s.OnBoot)
	w.line("startup:")
	w.line("  main_order: %d", s.Startup.MainOrder)
	w.line("  main_delay_sec: %d", s.Startup.MainDelaySec)
	w.line("  node_order: %d", s.Startup.NodeOrder)
	w.line("  node_delay_sec: %d", s.Startup.NodeDelaySec)
	return w.b.String()
}

func orNone(s string) string {
	if s == "" {
		return "unknown"
	}
	return s
}
